import { chmod, copyFile, mkdir, rename, stat, writeFile } from 'fs/promises'
import { rootDir } from '../utils'
import { host, recoveryPath, writePrivate } from './snapshot'
import { databasePath, Instance, makeTools } from './tools'

/**
 * The BLAKE2b instance's files under recovery/blake2b/: a copy of the
 * node's database and secrets, run offline by the fork against the BLAKE2b
 * service, and the pre-recovery safety backup the migration takes.
 */

/** A path inside the lightning subcontainer, as the package's own process sees it. */
export const hostPath = (containerPath: string) =>
  host(containerPath.replace(`${rootDir}/`, ''))

const exists = (path: string) =>
  stat(path).then(
    () => true,
    () => false,
  )

/**
 * The marker file left beside every database copy. A Lightning database older
 * than the channels' latest state can broadcast a revoked commitment and lose
 * the channel to a penalty, so no copy is ever restored by this package.
 */
export const doNotRestoreText = (what: string, takenAt: string) =>
  [
    'DO NOT RESTORE THIS DATABASE.',
    '',
    `${what}, taken ${takenAt}.`,
    '',
    'A Lightning channel database is only safe at its latest state. Starting a',
    'node on an older copy can broadcast a revoked commitment transaction, which',
    'lets the channel peer take the whole channel balance as a penalty. Nothing',
    'in this package restores a copy, and you should not either. Once every',
    'channel is closed and resolved, an old database has no value and only risk.',
    '',
    "hsm_secret (the node's key) and emergency.recover are the files worth",
    'keeping; both are in this directory.',
    '',
  ].join('\n')

/** The config the BLAKE2b instance runs with: no peers, no plugins, no ports. */
export function blake2bConfigText(opts: {
  network: string
  bridge: { host: string; port: number } | null
  cookieDir: string
  /** Regtest only: the fork's test activation height. */
  activationHeight?: number
}) {
  return [
    '# Generated by the Recovery actions for the BLAKE2b instance. Not read by',
    '# the primary instance; rewritten at every start.',
    `network=${opts.network}`,
    ...(opts.bridge
      ? [
          `bitcoin-rpcconnect=${opts.bridge.host}`,
          `bitcoin-rpcport=${opts.bridge.port}`,
        ]
      : []),
    `bitcoin-datadir=${opts.cookieDir}`,
    // No peer connections and no listening: the instance only watches the
    // chain, resolves closes and spends its wallet.
    'offline',
    // Both instances share one container: without this, connectd would still
    // bind the network's default port at start, even offline, and on mainnet
    // that is the primary's 9735.
    'autolisten=false',
    // dev-rescan-outputs (Recovery: Repair Wallet).
    'developer',
    ...(opts.network === 'regtest' && opts.activationHeight
      ? [`dev-blake2b-activation-height=${opts.activationHeight}`]
      : []),
    'log-level=info',
    '',
  ].join('\n')
}

/**
 * Creates the BLAKE2b instance from the primary's data, or completes an
 * earlier attempt: the database copy is taken once (SQLite's online backup
 * API, consistent with the primary running), the secrets are copied, and the
 * config is rewritten every time. `sub` is a subcontainer with the main
 * volume mounted.
 */
export async function createBlake2bInstance(
  sub: Parameters<typeof makeTools>[0],
  primary: Instance,
  blake2b: Instance,
  config: Parameters<typeof blake2bConfigText>[0],
) {
  const dir = `${blake2b.lightningDir}/${blake2b.network}`
  await mkdir(hostPath(dir), { recursive: true, mode: 0o700 })
  await chmod(hostPath(blake2b.lightningDir), 0o700)
  await chmod(hostPath(dir), 0o700)

  const database = databasePath(blake2b)
  let copied = false
  if (!(await exists(hostPath(database)))) {
    // Into a temporary name first, so a copy that dies half way is not
    // mistaken for a database at the next start.
    const tmp = `${database}.copying`
    await makeTools(sub, primary).sqliteBackup(tmp)
    await chmod(hostPath(tmp), 0o600)
    await rename(hostPath(tmp), hostPath(database))
    copied = true
  }
  for (const name of ['hsm_secret', 'emergency.recover']) {
    const from = hostPath(`${primary.lightningDir}/${primary.network}/${name}`)
    const to = hostPath(`${dir}/${name}`)
    if (await exists(to)) continue
    await copyFile(from, to).catch(() => {})
    await chmod(to, 0o600).catch(() => {})
  }
  await writeFile(
    hostPath(`${blake2b.lightningDir}/DO-NOT-RESTORE.txt`),
    doNotRestoreText(
      "The BLAKE2b instance of a recovery: a copy of the node's database made after its channels were closed on the SHA256d chain",
      new Date().toISOString(),
    ),
    { mode: 0o600 },
  )
  await writeFile(
    hostPath(`${blake2b.lightningDir}/config`),
    blake2bConfigText(config),
    { mode: 0o600 },
  )
  return { copied, database }
}

/** Where the migration keeps the state the recovery started from. */
export const preRecoveryPath = `${recoveryPath}/pre-recovery`

/**
 * The safety backup the migration takes before the first start of this
 * build, with the node stopped: a plain file copy is consistent then, and a
 * migration has no subcontainer to run sqlite3 in. Never overwrites an
 * earlier one: the first is the one that matters.
 */
export async function preRecoveryBackup(network: string) {
  if (await exists(host(preRecoveryPath))) return { taken: false, files: [] }
  await mkdir(host(recoveryPath), { recursive: true, mode: 0o700 })
  await mkdir(host(preRecoveryPath), { mode: 0o700 })
  const files: string[] = []
  for (const [from, to] of [
    [`${network}/lightningd.sqlite3`, 'lightningd.sqlite3'],
    [`${network}/lightningd.sqlite3-wal`, 'lightningd.sqlite3-wal'],
    [`${network}/lightningd.sqlite3-shm`, 'lightningd.sqlite3-shm'],
    [`${network}/hsm_secret`, 'hsm_secret'],
    [`${network}/emergency.recover`, 'emergency.recover'],
    ['config', 'config'],
    ['store.json', 'store.json'],
  ]) {
    const dest = `${preRecoveryPath}/${to}`
    const ok = await copyFile(host(from), host(dest)).then(
      () => true,
      () => false,
    )
    if (!ok) continue
    await chmod(host(dest), 0o600)
    files.push(to)
  }
  await writePrivate(
    `${preRecoveryPath}/DO-NOT-RESTORE.txt`,
    doNotRestoreText(
      'The state of this node when the recovery build was installed, before any channel was closed',
      new Date().toISOString(),
    ),
  )
  return { taken: true, files }
}
